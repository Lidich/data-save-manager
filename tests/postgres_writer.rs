#[tokio::test]
#[ignore = "requires local PostgreSQL"]
async fn counted_prepared_replay_preserves_newer_updates_and_generated_rows() -> Result<()> {
    let fixture = Fixture::new(true).await?;
    let writer = fixture.writer(timeouts());
    let id = Uuid::new_v4();
    let original = json!([{ "id": 10000, "value": 1 }, { "value": 2 }]);
    assert_eq!(
        writer
            .write_prepared(id, QUEUE, || Ok(PreparedBatch::with_count_sql(
                UPSERT_COUNT_SQL,
                original.clone()
            )))
            .await?,
        2
    );
    assert_eq!(
        writer
            .write_prepared(Uuid::new_v4(), QUEUE, || Ok(PreparedBatch::with_count_sql(
                UPSERT_COUNT_SQL,
                json!([{ "id": 10000, "value": 9 }])
            )))
            .await?,
        1
    );
    assert_eq!(
        writer
            .write_prepared(id, QUEUE, || Ok(PreparedBatch::with_count_sql(
                UPSERT_COUNT_SQL,
                original
            )))
            .await?,
        0
    );
    let values: Vec<i32> = sqlx::query_scalar("SELECT value FROM records ORDER BY value")
        .fetch_all(&fixture.pool)
        .await?;
    assert_eq!(values, vec![2, 9]);
    assert_eq!(fixture.receipt_count(id).await?, 1);
    drop(writer);
    fixture.close().await
}

