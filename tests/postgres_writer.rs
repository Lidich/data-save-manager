#[tokio::test]
#[ignore = "requires local PostgreSQL"]
async fn slow_synchronous_prepare_exceeding_deadline_never_submits_sql() -> Result<()> {
    let fixture = Fixture::new(true).await?;
    let proxy = ResponseProxy::start(&fixture.pool.connect_options()).await?;
    let proxy_pool = proxy.pool(&fixture.pool.connect_options());
    let limits = timeouts();
    let writer = DatabaseWriter::new(proxy_pool.clone(), limits);
    writer.check_ready().await?;
    let submitted_before = proxy.submitted_queries.load(Ordering::SeqCst);
    let id = Uuid::new_v4();
    let error = timeout(
        WATCHDOG,
        writer.write_prepared(id, QUEUE, || {
            std::thread::sleep(limits.batch() + Duration::from_millis(200));
            Ok(prepared(json!([{ "value": 1 }])))
        }),
    )
    .await?
    .unwrap_err();
    failure(&error, id, "client_deadline", None);
    assert_eq!(
        error.downcast_ref::<WriteFailure>().unwrap().stage,
        "prepare"
    );
    tokio::time::sleep(Duration::from_millis(100)).await;
    assert_eq!(
        proxy.submitted_queries.load(Ordering::SeqCst),
        submitted_before
    );
    assert_eq!(fixture.counts().await?, (0, 0));
    assert_eq!(fixture.receipt_count(id).await?, 0);
    assert_eq!(
        timeout(
            WATCHDOG,
            writer.write_prepared(id, QUEUE, || Ok(prepared(json!([{ "value": 1 }]))))
        )
        .await??,
        1
    );
    drop(writer);
    proxy_pool.close().await;
    proxy.stop().await;
    fixture.close().await
}

struct ResponseProxy {
    port: u16,
    drop_all: Arc<AtomicBool>,
    drop_commit: Arc<AtomicBool>,
    dropped_commits: Arc<AtomicUsize>,
    submitted_queries: Arc<AtomicUsize>,
    task: JoinHandle<()>,
}

impl ResponseProxy {
    async fn start(upstream: &PgConnectOptions) -> Result<Self> {
        let listener = TcpListener::bind("127.0.0.1:0").await?;
        let port = listener.local_addr()?.port();
        let host = upstream.get_host().to_owned();
        let upstream_port = upstream.get_port();
        let drop_all = Arc::new(AtomicBool::new(false));
        let drop_commit = Arc::new(AtomicBool::new(false));
        let dropped_commits = Arc::new(AtomicUsize::new(0));
        let submitted_queries = Arc::new(AtomicUsize::new(0));
        let all = drop_all.clone();
        let commit = drop_commit.clone();
        let dropped = dropped_commits.clone();
        let submitted = submitted_queries.clone();
        let task = tokio::spawn(async move {
            let mut clients = JoinSet::new();
            loop {
                tokio::select! {
                    client = listener.accept() => {
                        let Ok((client, _)) = client else { break };
                        let host = host.clone();
                        let all = all.clone();
                        let commit = commit.clone();
                        let dropped = dropped.clone();
                        let submitted = submitted.clone();
                        clients.spawn(async move {
                            let server = TcpStream::connect((host.as_str(), upstream_port)).await?;
                            let (mut cr, mut cw) = client.into_split();
                            let (mut sr, mut sw) = server.into_split();
                            tokio::select! {
                                result = async {
                                    let length = cr.read_u32().await?;
                                    if !(8..=16 * 1024 * 1024).contains(&length) {
                                        return Err(io::Error::new(io::ErrorKind::InvalidData, "invalid startup frame"));
                                    }
                                    let mut startup = vec![0; length as usize - 4];
                                    cr.read_exact(&mut startup).await?;
                                    sw.write_all(&length.to_be_bytes()).await?;
                                    sw.write_all(&startup).await?;
                                    loop {
                                        let mut header = [0_u8; 5];
                                        match cr.read_exact(&mut header).await {
                                            Ok(_) => {}
                                            Err(error) if error.kind() == io::ErrorKind::UnexpectedEof => break,
                                            Err(error) => return Err(error),
                                        }
                                        let length = u32::from_be_bytes(header[1..].try_into().unwrap()) as usize;
                                        if !(4..=16 * 1024 * 1024).contains(&length) {
                                            return Err(io::Error::new(io::ErrorKind::InvalidData, "invalid frontend frame"));
                                        }
                                        let mut body = vec![0; length - 4];
                                        cr.read_exact(&mut body).await?;
                                        if matches!(header[0], b'Q' | b'E') {
                                            submitted.fetch_add(1, Ordering::SeqCst);
                                        }
                                        sw.write_all(&header).await?;
                                        sw.write_all(&body).await?;
                                    }
                                    Ok::<(), io::Error>(())
                                } => { result?; }
                                result = async {
                                    let mut suppress = false;
                                    loop {
                                        let mut header = [0_u8; 5];
                                        match sr.read_exact(&mut header).await {
                                            Ok(_) => {}
                                            Err(error) if error.kind() == io::ErrorKind::UnexpectedEof => break,
                                            Err(error) => return Err(error),
                                        }
                                        let length = u32::from_be_bytes(header[1..].try_into().unwrap()) as usize;
                                        if !(4..=16 * 1024 * 1024).contains(&length) {
                                            return Err(io::Error::new(io::ErrorKind::InvalidData, "invalid PostgreSQL frame"));
                                        }
                                        let mut body = vec![0; length - 4];
                                        sr.read_exact(&mut body).await?;
                                        if header[0] == b'C' && body == b"COMMIT\0" && commit.swap(false, Ordering::SeqCst) {
                                            suppress = true;
                                            dropped.fetch_add(1, Ordering::SeqCst);
                                        }
                                        if !suppress && !all.load(Ordering::SeqCst) {
                                            cw.write_all(&header).await?;
                                            cw.write_all(&body).await?;
                                        }
                                    }
                                    Ok::<(), io::Error>(())
                                } => { result?; }
                            }
                            Ok::<(), io::Error>(())
                        });
                    }
                    _ = clients.join_next(), if !clients.is_empty() => {}
                }
            }
        });
        Ok(Self {
            port,
            drop_all,
            drop_commit,
            dropped_commits,
            submitted_queries,
            task,
        })
    }

    fn pool(&self, upstream: &PgConnectOptions) -> PgPool {
        PgPoolOptions::new()
            .max_connections(2)
            .acquire_timeout(WATCHDOG)
            .connect_lazy_with(
                upstream
                    .clone()
                    .host("127.0.0.1")
                    .port(self.port)
                    .ssl_mode(PgSslMode::Disable),
            )
    }

    async fn stop(&self) {
        self.task.abort();
        while !self.task.is_finished() {
            tokio::task::yield_now().await;
        }
    }
}

impl Drop for ResponseProxy {
    fn drop(&mut self) {
        self.task.abort();
    }
}

async fn wait_for_commit(fixture: &Fixture, id: Uuid) -> Result<()> {
    timeout(WATCHDOG, async {
        loop {
            if fixture.receipt_count(id).await? == 1 {
                return Ok::<(), anyhow::Error>(());
            }
            tokio::time::sleep(Duration::from_millis(10)).await;
        }
    })
    .await??;
    Ok(())
}

#[tokio::test]
#[ignore = "requires local PostgreSQL"]
async fn prepared_lost_commit_response_retries_without_duplicate_rows() -> Result<()> {
    let fixture = Fixture::new(true).await?;
    let proxy = ResponseProxy::start(&fixture.pool.connect_options()).await?;
    let proxy_pool = proxy.pool(&fixture.pool.connect_options());
    let writer = DatabaseWriter::new(proxy_pool.clone(), timeouts());
    timeout(WATCHDOG, writer.check_ready()).await??;
    assert_eq!(
        writer
            .write_prepared(Uuid::new_v4(), QUEUE, || Ok(prepared(json!([]))))
            .await?,
        0
    );
    let id = Uuid::new_v4();
    proxy.drop_all.store(true, Ordering::SeqCst);
    let pending_writer = writer.clone();
    let mut tasks = JoinSet::new();
    tasks.spawn(async move {
        pending_writer
            .write_prepared(id, QUEUE, || Ok(prepared(json!([{ "value": 5 }]))))
            .await
    });
    wait_for_commit(&fixture, id).await?;
    let error = timeout(WATCHDOG, tasks.join_next())
        .await?
        .unwrap()?
        .unwrap_err();
    failure(&error, id, "client_deadline", None);
    proxy.drop_all.store(false, Ordering::SeqCst);
    assert_eq!(
        timeout(
            WATCHDOG,
            writer.write_prepared(id, QUEUE, || Ok(prepared(json!([{ "value": 5 }]))))
        )
        .await??,
        0
    );
    assert_eq!(fixture.counts().await?, (1, 0));
    assert_eq!(fixture.receipt_count(id).await?, 1);
    drop(writer);
    proxy_pool.close().await;
    proxy.stop().await;
    fixture.close().await
}

