#[tokio::test]
#[ignore = "requires local PostgreSQL"]
async fn concurrent_prepared_same_id_inserts_exactly_once() -> Result<()> {
    let fixture = Fixture::new(true).await?;
    let id = Uuid::new_v4();
    let barrier = Arc::new(Barrier::new(2));
    let mut tasks = JoinSet::new();
    for _ in 0..2 {
        let writer = fixture.writer(timeouts());
        let barrier = barrier.clone();
        tasks.spawn(async move {
            writer.check_ready().await?;
            barrier.wait().await;
            writer
                .write_prepared(id, QUEUE, || Ok(prepared(json!([{ "value": 1 }]))))
                .await
        });
    }
    let mut results = Vec::new();
    while let Some(result) = timeout(WATCHDOG, tasks.join_next()).await? {
        results.push(result??);
    }
    results.sort_unstable();
    assert_eq!(results, vec![0, 1]);
    assert_eq!(fixture.counts().await?, (1, 0));
    assert_eq!(fixture.receipt_count(id).await?, 1);
    fixture.close().await
}

#[tokio::test]
#[ignore = "requires local PostgreSQL"]
async fn concurrent_transaction_same_id_executes_callback_exactly_once() -> Result<()> {
    let fixture = Fixture::new(true).await?;
    let id = Uuid::new_v4();
    let entered = Arc::new(Notify::new());
    let release = Arc::new(Notify::new());
    let mut first_batch = PairBatch::new();
    first_batch.pause = Pause::Gate {
        entered: entered.clone(),
        release: release.clone(),
    };
    let first_calls = first_batch.calls.clone();
    let second_batch = PairBatch::new();
    let second_calls = second_batch.calls.clone();
    let first = fixture.writer(timeouts());
    let second = fixture.writer(timeouts());
    first.check_ready().await?;
    second.check_ready().await?;
    let mut tasks = JoinSet::new();
    tasks.spawn(async move { first.write_transaction(id, QUEUE, &first_batch).await });
    timeout(WATCHDOG, entered.notified()).await?;
    let mut replay = Box::pin(second.write_transaction(id, QUEUE, &second_batch));
    assert!(timeout(Duration::from_millis(50), &mut replay)
        .await
        .is_err());
    assert_eq!(second_calls.load(Ordering::SeqCst), 0);
    release.notify_one();
    assert_eq!(timeout(WATCHDOG, tasks.join_next()).await?.unwrap()??, 2);
    assert_eq!(timeout(WATCHDOG, replay).await??, 0);
    assert_eq!(first_calls.load(Ordering::SeqCst), 1);
    assert_eq!(second_calls.load(Ordering::SeqCst), 0);
    assert_eq!(fixture.counts().await?, (1, 1));
    assert_eq!(fixture.receipt_count(id).await?, 1);
    drop(second);
    fixture.close().await
}

async fn lock_timeout_case(transactional: bool) -> Result<()> {
    let fixture = Fixture::new(true).await?;
    let limits = WriteTimeouts::new(
        Duration::from_secs(3),
        Duration::from_secs(2),
        Duration::from_millis(100),
    )?;
    let writer = fixture.writer(limits);
    writer.check_ready().await?;
    let mut held = fixture.pool.begin().await?;
    sqlx::query("LOCK TABLE records IN ACCESS EXCLUSIVE MODE")
        .execute(&mut *held)
        .await?;
    let id = Uuid::new_v4();
    let batch = PairBatch::new();
    let result = if transactional {
        timeout(WATCHDOG, writer.write_transaction(id, QUEUE, &batch)).await?
    } else {
        timeout(
            WATCHDOG,
            writer.write_prepared(id, QUEUE, || Ok(prepared(json!([{ "value": 1 }])))),
        )
        .await?
    };
    held.rollback().await?;
    failure(&result.unwrap_err(), id, "lock_timeout", Some("55P03"));
    assert_eq!(fixture.receipt_count(id).await?, 0);
    assert_eq!(fixture.counts().await?, (0, 0));
    if transactional {
        assert_eq!(
            timeout(WATCHDOG, writer.write_transaction(id, QUEUE, &batch)).await??,
            2
        );
    } else {
        assert_eq!(
            timeout(
                WATCHDOG,
                writer.write_prepared(id, QUEUE, || Ok(prepared(json!([{ "value": 1 }]))))
            )
            .await??,
            1
        );
    }
    drop(writer);
    fixture.close().await
}

