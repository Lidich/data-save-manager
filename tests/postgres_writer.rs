const WATCHDOG: Duration = Duration::from_secs(10);
const QUEUE: &str = "test_records";
const INSERT_SQL: &str = "INSERT INTO records (value) \
    SELECT value FROM jsonb_to_recordset((SELECT payload FROM data_save_input)) AS r(value integer)";
const UPSERT_COUNT_SQL: &str = ", explicit_rows AS ( \
    INSERT INTO records (id, value) \
    SELECT id, value FROM jsonb_to_recordset((SELECT payload FROM data_save_input)) AS r(id bigint, value integer) \
    WHERE id IS NOT NULL ON CONFLICT (id) DO UPDATE SET value = EXCLUDED.value RETURNING id \
    ), generated_rows AS ( \
    INSERT INTO records (value) \
    SELECT value FROM jsonb_to_recordset((SELECT payload FROM data_save_input)) AS r(id bigint, value integer) \
    WHERE id IS NULL RETURNING id \
    ) SELECT (SELECT count(*) FROM explicit_rows) + (SELECT count(*) FROM generated_rows)";

struct Fixture {
    admin: PgPool,
    pool: PgPool,
    schema: String,
}

impl Fixture {
    async fn new(receipts: bool) -> Result<Self> {
        let url = env::var("DSM_TEST_DATABASE_URL")
            .context("set DSM_TEST_DATABASE_URL explicitly to a local PostgreSQL test database")?;
        let options: PgConnectOptions = url.parse()?;
        if !matches!(options.get_host(), "localhost" | "127.0.0.1" | "::1") {
            bail!("DSM_TEST_DATABASE_URL must target localhost, 127.0.0.1 or ::1");
        }
        let options = options.ssl_mode(PgSslMode::Disable);
        let admin = PgPoolOptions::new()
            .max_connections(2)
            .acquire_timeout(WATCHDOG)
            .connect_with(options.clone())
            .await?;
        let schema = format!("dsm_writer_{}", Uuid::new_v4().simple());
        sqlx::query(&format!("CREATE SCHEMA {schema}"))
            .execute(&admin)
            .await?;
        let pool = PgPoolOptions::new()
            .max_connections(5)
            .acquire_timeout(WATCHDOG)
            .connect_with(options.options([("search_path", schema.as_str())]))
            .await?;
        sqlx::raw_sql(
            "CREATE TABLE records (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value integer NOT NULL); \
             CREATE TABLE audit (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, record_id bigint NOT NULL REFERENCES records(id), value integer NOT NULL)",
        ).execute(&pool).await?;
        let fixture = Self {
            admin,
            pool,
            schema,
        };
        if receipts {
            fixture.create_receipts().await?;
        }
        Ok(fixture)
    }

    async fn create_receipts(&self) -> Result<()> {
        sqlx::query("CREATE TABLE data_save_batches (batch_id uuid PRIMARY KEY, queue text NOT NULL, committed_at timestamptz NOT NULL DEFAULT now())")
            .execute(&self.pool).await?;
        Ok(())
    }

    fn writer(&self, timeouts: WriteTimeouts) -> DatabaseWriter {
        DatabaseWriter::new(self.pool.clone(), timeouts)
    }

    async fn receipt_count(&self, id: Uuid) -> Result<i64> {
        Ok(
            sqlx::query_scalar("SELECT count(*) FROM data_save_batches WHERE batch_id = $1")
                .bind(id)
                .fetch_one(&self.pool)
                .await?,
        )
    }

    async fn counts(&self) -> Result<(i64, i64)> {
        Ok(
            sqlx::query_as("SELECT (SELECT count(*) FROM records), (SELECT count(*) FROM audit)")
                .fetch_one(&self.pool)
                .await?,
        )
    }

    async fn close(self) -> Result<()> {
        self.pool.close().await;
        sqlx::query(&format!("DROP SCHEMA {} CASCADE", self.schema))
            .execute(&self.admin)
            .await?;
        self.admin.close().await;
        Ok(())
    }
}

fn timeouts() -> WriteTimeouts {
    WriteTimeouts::new(
        Duration::from_secs(3),
        Duration::from_secs(2),
        Duration::from_millis(500),
    )
    .unwrap()
}

fn prepared(rows: Value) -> PreparedBatch {
    PreparedBatch::new(INSERT_SQL, rows)
}

fn failure(error: &anyhow::Error, id: Uuid, kind: &str, sqlstate: Option<&str>) {
    let failure = error
        .downcast_ref::<WriteFailure>()
        .expect("structured WriteFailure");
    assert_eq!(failure.batch_id, id);
    assert_eq!(failure.queue, QUEUE);
    assert_eq!(failure.kind, kind, "{error:#}");
    assert_eq!(failure.sqlstate.as_deref(), sqlstate, "{error:#}");
}

enum Pause {
    None,
    Rust,
    Sql,
    Gate {
        entered: Arc<Notify>,
        release: Arc<Notify>,
    },
}

struct PairBatch {
    calls: Arc<AtomicUsize>,
    fail_second: bool,
    pause: Pause,
}

impl PairBatch {
    fn new() -> Self {
        Self {
            calls: Arc::new(AtomicUsize::new(0)),
            fail_second: false,
            pause: Pause::None,
        }
    }
}

impl TransactionBatch for PairBatch {
    async fn execute(&self, connection: &mut PgConnection) -> Result<u64> {
        self.calls.fetch_add(1, Ordering::SeqCst);
        let id: i64 = sqlx::query_scalar("INSERT INTO records(value) VALUES (7) RETURNING id")
            .fetch_one(&mut *connection)
            .await?;
        match &self.pause {
            Pause::None => {}
            Pause::Rust => tokio::time::sleep(Duration::from_secs(30)).await,
            Pause::Sql => {
                sqlx::query("SELECT pg_sleep(30)")
                    .execute(&mut *connection)
                    .await?;
            }
            Pause::Gate { entered, release } => {
                entered.notify_one();
                release.notified().await;
            }
        }
        let value = if self.fail_second { None } else { Some(7_i32) };
        sqlx::query("INSERT INTO audit(record_id, value) VALUES ($1, $2)")
            .bind(id)
            .bind(value)
            .execute(&mut *connection)
            .await?;
        Ok(2)
    }
}

