#[tokio::test]
#[ignore = "requires local PostgreSQL"]
async fn configured_timezone_applies_to_both_paths_and_survives_reconnect() -> Result<()> {
    let fixture = Fixture::new(true).await?;
    let utc_writer = fixture.writer(timeouts());
    utc_writer.check_ready().await?;
    let utc_batch = TimezoneBatch {
        expected: "UTC",
        pids: Mutex::new(Vec::new()),
        fail: false,
    };
    utc_writer
        .write_transaction(Uuid::new_v4(), QUEUE, &utc_batch)
        .await?;
    let writer = utc_writer.clone().with_timezone("Europe/Moscow");
    let mut batch = TimezoneBatch {
        expected: "Europe/Moscow",
        pids: Mutex::new(Vec::new()),
        fail: false,
    };
    for _ in 0..2 {
        assert_eq!(
            writer
                .write_transaction(Uuid::new_v4(), QUEUE, &batch)
                .await?,
            0
        );
    }
    assert_eq!(writer.write_prepared(Uuid::new_v4(), QUEUE, || {
        Ok(PreparedBatch::new(
            "INSERT INTO records(value) SELECT CASE WHEN current_setting('TimeZone') = 'Europe/Moscow' THEN 3 ELSE 0 END FROM data_save_input",
            json!([]),
        ))
    }).await?, 1);
    let value: i32 = sqlx::query_scalar("SELECT value FROM records")
        .fetch_one(&fixture.pool)
        .await?;
    assert_eq!(value, 3);
    let failed_id = Uuid::new_v4();
    batch.fail = true;
    let error = writer
        .write_transaction(failed_id, QUEUE, &batch)
        .await
        .unwrap_err();
    assert!(format!("{error:#}").contains("timezone reconnect sentinel"));
    assert_eq!(fixture.receipt_count(failed_id).await?, 0);
    batch.fail = false;
    assert_eq!(
        timeout(WATCHDOG, writer.write_transaction(failed_id, QUEUE, &batch)).await??,
        0
    );
    let pids = batch.pids.into_inner().unwrap();
    assert_eq!(pids.len(), 4);
    assert_eq!(pids[0], pids[1]);
    assert_eq!(pids[1], pids[2]);
    assert_ne!(
        pids[2], pids[3],
        "failure must discard the dedicated connection"
    );
    utc_writer
        .write_transaction(Uuid::new_v4(), QUEUE, &utc_batch)
        .await?;
    let utc_pids = utc_batch.pids.into_inner().unwrap();
    assert_eq!(utc_pids.len(), 2);
    assert_eq!(
        utc_pids[0], utc_pids[1],
        "original clone keeps its UTC connection"
    );
    assert_ne!(
        utc_pids[0], pids[0],
        "configured clone opens its own connection"
    );
    drop(writer);
    drop(utc_writer);
    fixture.close().await
}

