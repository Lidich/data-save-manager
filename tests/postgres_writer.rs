struct TimezoneBatch {
    expected: &'static str,
    pids: Mutex<Vec<i32>>,
    fail: bool,
}

impl TransactionBatch for TimezoneBatch {
    async fn execute(&self, connection: &mut PgConnection) -> Result<u64> {
        let (pid, timezone): (i32, String) =
            sqlx::query_as("SELECT pg_backend_pid(), current_setting('TimeZone')")
                .fetch_one(connection)
                .await?;
        assert_eq!(timezone, self.expected);
        self.pids.lock().unwrap().push(pid);
        if self.fail {
            bail!("timezone reconnect sentinel");
        }
        Ok(0)
    }
}

